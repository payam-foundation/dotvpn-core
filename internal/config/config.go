// Package config is the YAML configuration of dotvpn-core. One file serves
// the node and control roles; each reads only its own section.
package config

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"

	"github.com/payam-foundation/dotvpn-core/internal/egress"
	"github.com/payam-foundation/dotvpn-wire/atomicfile"
	"github.com/payam-foundation/dotvpn-wire/loopback"
)

// Config is the root of the YAML file.
type Config struct {
	DataDir string        `yaml:"data_dir"`
	Node    NodeConfig    `yaml:"node"`
	Control ControlConfig `yaml:"control"`
}

// NodeConfig is the edge proxy section.
type NodeConfig struct {
	Name string `yaml:"name"`
	// Listen is the TLS listen address shared by h2, h3, cdnws and webtunnel.
	Listen string `yaml:"listen"`
	// Domain enables ACME certificates and is the SNI the node answers to.
	// Empty means a self-signed certificate that clients pin.
	Domain string `yaml:"domain"`
	// AltDomains are extra names for this node that get ACME certificates too.
	// Each must resolve to this host (HTTP-01/TLS-ALPN-01 validation).
	AltDomains []string `yaml:"alt_domains"`
	ACMEEmail  string   `yaml:"acme_email"`
	// Decoy is what non-proxy visitors see: empty for the built-in page,
	// "dir:/path" for static files, or an https:// URL to reverse proxy.
	Decoy string `yaml:"decoy"`
	// AllowedPorts limits egress destinations.
	AllowedPorts []int `yaml:"allowed_ports"`
	// AllowedUDPPorts limits UDP flow destinations (default 53, 123, 443, 3478).
	AllowedUDPPorts []int `yaml:"allowed_udp_ports"`
	// ConcPerUser and MbpsPerUser are defaults when a token carries no limits.
	ConcPerUser int `yaml:"conc_per_user"`
	MbpsPerUser int `yaml:"mbps_per_user"`
	// TrustedKeys are base64url Ed25519 public keys allowed to sign tokens.
	TrustedKeys []string `yaml:"trusted_keys"`
	// Advertise is the host:port clients should use for this node.
	Advertise string `yaml:"advertise"`
	// Hidden keeps this node's address out of every client list: clients
	// reach it only through relays (reverse tunnels the node dials out).
	Hidden bool `yaml:"hidden"`
	// AdminListen serves /healthz, /readyz and /metrics. Loopback address
	// ("127.0.0.1:9100") or "unix:/path"; anything else is refused.
	AdminListen string `yaml:"admin_listen"`
	// IdentityKey is the node's base64url Ed25519 private key. Clients pin its
	// public half when they reach the node through a relay. Generated by init
	// or on first start.
	IdentityKey string `yaml:"identity_key"`
	// Relays are static relay references for nodes without a control plane;
	// joined nodes receive theirs from control on every heartbeat.
	Relays []RelayRef `yaml:"relays"`
	// Join connects the node to a control plane.
	Join JoinConfig `yaml:"join"`
	// Transports enabled on this node.
	Transports NodeTransports `yaml:"transports"`
	// Egress routes outbound connections: exits, blocklist, rules, IP family.
	// Unset means every destination is dialled directly from the server.
	Egress egress.Config `yaml:"egress,omitempty"`
}

// RelayRef is a relay the node dials out to and keeps a pool of tunnels to.
type RelayRef struct {
	ID   string `yaml:"id"`
	Addr string `yaml:"addr"`
	SNI  string `yaml:"sni"`
	// Key is the relay's base64url Ed25519 public key.
	Key string `yaml:"key"`
}

// JoinConfig connects a node to a control plane.
type JoinConfig struct {
	URL   string `yaml:"url"`
	Token string `yaml:"token"`
	// ID and Secret are filled in after the first successful join.
	ID     string `yaml:"id"`
	Secret string `yaml:"secret"`
}

// NodeTransports selects the carriers a node serves.
type NodeTransports struct {
	H3 bool `yaml:"h3"`
	// CDNWSPath enables the WebSocket carrier for CDNs on this URL path.
	CDNWSPath string `yaml:"cdnws_path"`
	// CDNHost is the CDN-proxied domain clients use for the cdnws carrier. The
	// CDN terminates TLS, so that endpoint carries no pin. Empty reuses the
	// node's own address.
	CDNHost string `yaml:"cdn_host"`
	// WebTunnelPath enables WebTunnel on this secret URL path.
	WebTunnelPath string `yaml:"webtunnel_path"`
	// Snowflake enables the embedded snowflake server on this listen address.
	Snowflake SnowflakeServer `yaml:"snowflake"`
}

// SnowflakeServer configures the embedded snowflake server.
type SnowflakeServer struct {
	// Listen is the TLS address volunteer proxies connect to (wss).
	Listen string `yaml:"listen"`
	// BrokerPath is the URL path on the node's main port where the embedded
	// broker is mounted. Needs a real domain: clients verify its certificate.
	BrokerPath string `yaml:"broker_path"`
	// RelayURL is the public wss:// URL of Listen, as proxies must dial it
	// (default wss://<advertise host><listen port>).
	RelayURL string `yaml:"relay_url"`
}

// ControlConfig is the control-plane section.
type ControlConfig struct {
	// Listen is the public API (tokens, server list, node and relay planes).
	Listen string `yaml:"listen"`
	// Domain gets an ACME certificate for the control listener when set.
	Domain string `yaml:"domain"`
	// PrivateKey is the base64url Ed25519 signing key. Generated by init.
	PrivateKey string `yaml:"private_key"`
	// AdminListen serves the admin API. Loopback address or "unix:/path";
	// anything else is refused. It is never mounted on a public port.
	AdminListen string `yaml:"admin_listen"`
	// AdminToken protects the admin API on top of the listener restriction.
	AdminToken string `yaml:"admin_token"`
	// Database is a SQLite path, or a postgres:// URL.
	Database string `yaml:"database"`
	TokenTTL string `yaml:"token_ttl"`
	// DefaultQuotaGB is the monthly quota for new accounts; 0 is unlimited.
	DefaultQuotaGB int `yaml:"default_quota_gb"`
	// Mount serves the public API on the node mux under this path prefix
	// (allinone), so a single port and certificate are used.
	Mount string `yaml:"mount"`
}

// Defaults fills unset fields. It never overwrites user values.
func (c *Config) Defaults() {
	if c.DataDir == "" {
		c.DataDir = "/var/lib/dotvpn"
	}
	n := &c.Node
	if n.Listen == "" {
		n.Listen = ":443"
	}
	if n.AdminListen == "" {
		n.AdminListen = "127.0.0.1:9100"
	}
	if len(n.AllowedPorts) == 0 {
		n.AllowedPorts = []int{80, 443, 8080, 8443}
	}
	if n.ConcPerUser == 0 {
		n.ConcPerUser = 256
	}
	if c.Control.Listen == "" {
		c.Control.Listen = "127.0.0.1:8080"
	}
	if c.Control.AdminListen == "" {
		c.Control.AdminListen = "127.0.0.1:8081"
	}
	if c.Control.TokenTTL == "" {
		c.Control.TokenTTL = "15m"
	}
	if c.Control.Database == "" {
		c.Control.Database = filepath.Join(c.DataDir, "control.db")
	}
}

// Validate checks settings that must fail at startup.
func (c *Config) Validate() error {
	if err := loopback.Check(c.Node.AdminListen); err != nil {
		return fmt.Errorf("node.admin_listen: %w", err)
	}
	if err := loopback.Check(c.Control.AdminListen); err != nil {
		return fmt.Errorf("control.admin_listen: %w", err)
	}
	if err := c.Node.Egress.Validate(); err != nil {
		return fmt.Errorf("node.egress: %w", err)
	}
	return nil
}

// Load reads, defaults and validates a config file.
func Load(path string) (*Config, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var c Config
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&c); err != nil && !errors.Is(err, io.EOF) {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	c.Defaults()
	if err := c.Validate(); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &c, nil
}

// Save writes the config with mode 0600 (it may hold secrets), atomically.
func Save(path string, c *Config) error {
	b, err := yaml.Marshal(c)
	if err != nil {
		return err
	}
	return atomicfile.Write(path, b, 0o750)
}
